#!/usr/bin/env python3
"""Generate Claude Code config from the Cursor config (single source of truth).

  .cursor/rules/**/*.mdc   -> .claude/rules/**/*.md   (only glob-scoped rules; `globs` -> `paths`)
  .cursor/agents/*.md      -> .claude/agents/*.md     (adds `tools` / `model` per role)
  .cursor/skills/**        -> .claude/skills/**       (links rewritten)

alwaysApply rules are NOT copied: they are distilled in CLAUDE.md, which points at
the .cursor sources for detail. Loading ~50 KB of always-on rules every session is
the wrong trade-off for Claude Code.

Usage: scripts/sync-claude-config.py [--check]
  --check   exit 1 if generated files differ from what is on disk (for CI / pre-push)
"""
import os
import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".cursor"
DST = ROOT / ".claude"

# Per-agent Claude frontmatter additions. Omitted `tools` = inherit everything
# (needed for MCP such as Playwright). Reviewers stay on a fast model per lean-loop.
AGENT_EXTRA = {
    "api-reviewer": ["tools: Read, Grep, Glob, Bash, Write", "model: sonnet"],
    "code-reviewer": ["tools: Read, Grep, Glob, Bash, Write", "model: sonnet"],
    "database-reviewer": ["tools: Read, Grep, Glob, Bash, Write", "model: sonnet"],
    "mcp-reviewer": ["tools: Read, Grep, Glob, Bash, Write", "model: sonnet"],
    "performance-evaluator": ["tools: Read, Grep, Glob, Bash, Write", "model: sonnet"],
    "doc-updater": ["tools: Read, Grep, Glob, Edit, Write", "model: sonnet"],
    "security-reviewer": ["tools: Read, Grep, Glob, Bash, Write"],  # auth/crypto: keep session model
    "frontend-evaluator": ["model: sonnet"],  # needs browser/Playwright MCP -> inherit tools
    "planner": [],
    "architect": [],
    "designer": [],
    "generator": [],
}

# Skills that must never auto-trigger (ship to main is human-requested only).
SKILL_USER_ONLY = {"push-to-main"}

HEADER = "<!-- GENERATED by scripts/sync-claude-config.py from {src} — edit the source, then re-run. -->\n"
LINK_RE = re.compile(r"\]\(([^)\s#]+)(#[^)\s]*)?\)")


def split_frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not m:
        return "", text
    return m.group(1), m.group(2)


def fm_value(fm, key):
    m = re.search(rf"^{key}:\s*(.*)$", fm, re.M)
    return m.group(1).strip() if m else None


def split_globs(value):
    """Split on commas that are not inside {braces}."""
    value = value.strip().strip('"').strip("'")
    parts, depth, cur = [], 0, ""
    for ch in value:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def rewrite_links(body, src_file, dst_file, keep_inside=None):
    """Re-point relative markdown links so they still resolve from the new location."""

    def fix(m):
        target, anchor = m.group(1), m.group(2) or ""
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("/"):
            return m.group(0)
        resolved = (src_file.parent / target).resolve()
        if keep_inside and keep_inside in resolved.parents:
            return m.group(0)
        if not resolved.exists():
            return m.group(0)
        rel = os.path.relpath(resolved, dst_file.parent)
        return f"]({Path(rel).as_posix()}{anchor})"

    return LINK_RE.sub(fix, body)


def build():
    out = {}  # Path -> str

    for mdc in sorted((SRC / "rules").rglob("*.mdc")):
        fm, body = split_frontmatter(mdc.read_text())
        globs = fm_value(fm, "globs")
        if not globs or (fm_value(fm, "alwaysApply") or "").lower() == "true":
            continue
        rel = mdc.relative_to(SRC / "rules").with_suffix(".md")
        dst = DST / "rules" / rel
        desc = (fm_value(fm, "description") or "").replace('"', "'")
        paths = "\n".join(f'  - "{g}"' for g in split_globs(globs))
        head = f'---\ndescription: "{desc}"\npaths:\n{paths}\n---\n'
        src_rel = mdc.relative_to(ROOT).as_posix()
        out[dst] = head + HEADER.format(src=src_rel) + rewrite_links(body, mdc, dst)

    for md in sorted((SRC / "agents").glob("*.md")):
        name = md.stem
        fm, body = split_frontmatter(md.read_text())
        extra = AGENT_EXTRA.get(name, [])
        dst = DST / "agents" / md.name
        head = "---\n" + fm + ("\n" + "\n".join(extra) if extra else "") + "\n---\n"
        out[dst] = head + HEADER.format(src=md.relative_to(ROOT).as_posix()) + rewrite_links(body, md, dst)

    for f in sorted((SRC / "skills").rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(SRC / "skills")
        dst = DST / "skills" / rel
        skill_dir = SRC / "skills" / rel.parts[0]
        if f.suffix != ".md":
            out[dst] = f.read_bytes()
            continue
        text = f.read_text()
        if f.name == "SKILL.md":
            fm, body = split_frontmatter(text)
            if rel.parts[0] in SKILL_USER_ONLY and "disable-model-invocation" not in fm:
                fm += "\ndisable-model-invocation: true"
            text = "---\n" + fm + "\n---\n" + HEADER.format(src=f.relative_to(ROOT).as_posix()) + body
        out[dst] = rewrite_links(text, f, dst, keep_inside=skill_dir)
    # skills/README.md is an index for Cursor; Claude reads skill descriptions instead.
    out.pop(DST / "skills" / "README.md", None)
    return out


def current_generated():
    found = set()
    for sub in ("rules", "agents", "skills"):
        base = DST / sub
        if base.exists():
            found |= {p for p in base.rglob("*") if p.is_file()}
    return found


def main():
    check = "--check" in sys.argv
    want = build()
    drift = []
    for path, content in want.items():
        data = content if isinstance(content, bytes) else content.encode()
        if not path.exists() or path.read_bytes() != data:
            drift.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    stale = current_generated() - set(want)
    for path in sorted(stale):
        drift.append(path)
        if not check:
            path.unlink()
    for p in sorted(drift):
        print(("drift: " if check else "wrote: ") + p.relative_to(ROOT).as_posix())
    if check and drift:
        print("Run scripts/sync-claude-config.py", file=sys.stderr)
        sys.exit(1)
    print(f"{len(want)} files in sync" if not drift or check is False else "")


if __name__ == "__main__":
    main()
